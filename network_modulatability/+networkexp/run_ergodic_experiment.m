function state = initialize_progress_state(totalGroups)
state = struct( ...
    'total', totalGroups, ...
    'completed', 0, ...
    'startTimer', tic, ...
    'lastLineLength', 0);
end

function state = update_progress_state(state, payload)
if nargin < 2 || isempty(payload)
    return
end

state.completed = state.completed + 1;
progressFraction = state.completed / max(state.total, 1);
elapsedSeconds = toc(state.startTimer);
if progressFraction > 0
    etaSeconds = max(elapsedSeconds / progressFraction - elapsedSeconds, 0);
else
    etaSeconds = NaN;
end

barWidth = 24;
filled = min(barWidth, floor(progressFraction * barWidth));
barText = ['[', repmat('#', 1, filled), repmat('-', 1, barWidth - filled), ']'];
lineText = sprintf( ...
    '  Progress %s %3d/%3d (%5.1f%%) elapsed=%s eta=%s latest n_per=%d success=%d/%d candidate=%d attempts=%d', ...
    barText, ...
    state.completed, ...
    state.total, ...
    100 * progressFraction, ...
    format_duration(elapsedSeconds), ...
    format_duration(etaSeconds), ...
    payload.nPerturbedEdges, ...
    payload.successCount, ...
    payload.requestedRepeatCount, ...
    payload.candidateCount, ...
    payload.attemptCount);
padding = repmat(' ', 1, max(0, state.lastLineLength - numel(lineText)));
fprintf('\r%s%s', lineText, padding);
state.lastLineLength = numel(lineText);

if state.completed >= state.total
    fprintf('\n');
    state.lastLineLength = 0;
end
end

function state = finalize_progress_state(state)
if state.lastLineLength > 0
    fprintf('\n');
    state.lastLineLength = 0;
end
end

function summary = summarize_repeats(repeats)
if isempty(repeats)
    summary = struct([]);
    return
end

summary = struct( ...
    'nPerturbedEdges', [repeats.nPerturbedEdges], ...
    'attemptCounts', [repeats.attemptCount], ...
    'successCounts', [repeats.successCount], ...
    'candidateCounts', [repeats.candidateCount], ...
    'failureCounts', [repeats.failureCount], ...
    'successRates', [repeats.successCount] ./ max([repeats.attemptCount], 1), ...
    'candidateRates', [repeats.candidateCount] ./ max([repeats.attemptCount], 1));
end

function log_ergodic_configuration(settings, runInParallel)
parallelText = ternary(runInParallel, 'on', 'off');
fprintf('  Config: solver=%s, searchWindow=%g, repeats=%d, repeatMode=%s, accounting=%s, parallel=%s\n', ...
    settings.solverName, ...
    settings.searchWindow, ...
    settings.numRepeat, ...
    settings.repeatMode, ...
    settings.repeatAccountingMode, ...
    parallelText);
fprintf('  Network: N=%d, weightPer=%g, nets=%s\n', ...
    settings.network.N, ...
    settings.weightPer, ...
    strjoin(cellstr(string(settings.nets)), ','));
end

function log_ergodic_summary(summary)
if isempty(summary)
    fprintf('  Summary: no repeat groups were generated.\n');
    return
end

fprintf('  Summary: total success=%d/%d groups, mean success rate=%.3f, mean candidate rate=%.3f\n', ...
    sum(summary.successCounts > 0), ...
    numel(summary.nPerturbedEdges), ...
    mean(summary.successRates), ...
    mean(summary.candidateRates));
end

function perturbation = strip_perturbation_mask(perturbation)
perturbation = rmfield(perturbation, 'mask');
end

function value = get_field_or_default(s, name, defaultValue)
if isfield(s, name)
    value = s.(name);
else
    value = defaultValue;
end
end

function text = format_duration(seconds)
if isempty(seconds) || ~isfinite(seconds)
    text = '--:--:--';
    return
end

seconds = max(0, round(seconds));
hours = floor(seconds / 3600);
minutes = floor(mod(seconds, 3600) / 60);
secs = mod(seconds, 60);
text = sprintf('%02d:%02d:%02d', hours, minutes, secs);
end

function value = ternary(condition, trueValue, falseValue)
if condition
    value = trueValue;
else
    value = falseValue;
end
end

function settings = ensure_field(settings, name, defaultValue)
if ~isfield(settings, name) || isempty(settings.(name))
    settings.(name) = defaultValue;
end
end

function ensure_directory(folderPath)
if exist(folderPath, 'dir') ~= 7
    mkdir(folderPath);
end
end

function log_repeat_group_summaries(repeatCells, numGroups)
if isempty(repeatCells)
    return
end

logIndices = unique([1, min(10, numGroups), min(25, numGroups), min(50, numGroups), numGroups]);
for i = 1:numel(logIndices)
    idx = logIndices(i);
    repeatGroup = repeatCells{idx};
    fprintf('  n_per=%d: success %d/%d, candidate=%d, attempts=%d\n', ...
        repeatGroup.nPerturbedEdges, ...
        repeatGroup.successCount, ...
        repeatGroup.requestedRepeatCount, ...
        repeatGroup.candidateCount, ...
        repeatGroup.attemptCount);
    if repeatGroup.failureCount > 0
        firstFailure = repeatGroup.samples(find(~[repeatGroup.samples.success], 1, 'first'));
        networkexp.log_orbit_result('First non-success sample', firstFailure, '    ');
    end
end
end

function runInParallel = prepare_parallel_pool(settings)
runInParallel = settings.useParallel && exist('parpool', 'file') == 2;
if ~runInParallel
    return
end

currentPool = gcp('nocreate');
if isempty(currentPool)
    fprintf('  Starting parallel pool...\n');
    if isempty(settings.numWorkers)
        parpool;
    else
        parpool(settings.numWorkers);
    end
end
end

function solverOptions = build_solver_options(modelSpec, params)
solverOptions = struct();
if ~isfield(modelSpec, 'buildSolverOptions') || isempty(modelSpec.buildSolverOptions)
    return
end

solverOptions = modelSpec.buildSolverOptions(params);
if isempty(solverOptions)
    solverOptions = struct();
elseif ~isstruct(solverOptions)
    error('networkexp:InvalidModelSolverOptions', ...
        'modelSpec.buildSolverOptions must return a struct or [].');
end
end
