function results = run_ergodic_experiment(settings, modelSpec)
%RUN_ERGODIC_EXPERIMENT Execute and save one ergodic network sweep per net.

settings = normalize_ergodic_settings(settings, modelSpec);
runInParallel = prepare_parallel_pool(settings);

networkDir = fileparts(fileparts(mfilename('fullpath')));
outputDir = fullfile(networkDir, settings.outputSubdir, ...
    sprintf('N = %d', settings.network.N));
ensure_directory(outputDir);

netNames = cellstr(string(settings.nets));
results = struct('filePath', {}, 'netName', {}, 'sourceSequenceIndex', {});

for idxNet = 1:numel(netNames)
    netName = netNames{idxNet};
    fprintf('Running %s ergodic sweep for %s...\n', modelSpec.name, netName);
    log_ergodic_configuration(settings, runInParallel);

    baselineNetworkSeed = networkexp.derive_seed(settings.randomSeed, idxNet, 1);
    [baselineOmega, baselineNetworkMetadata] = networkexp.build_network_matrix( ...
        settings.network, netName, baselineNetworkSeed);
    baselineParams = modelSpec.buildParams(baselineOmega);
    baselineSolverOptions = build_solver_options(modelSpec, baselineParams);
    baselineResult = networkexp.evaluate_periodic_orbit( ...
        modelSpec.rhs, ...
        modelSpec.makeInitialState(settings.network.N), ...
        baselineParams, ...
        settings.solverName, ...
        settings.searchWindow, ...
        baselineSolverOptions);
    networkexp.log_orbit_result('Baseline', baselineResult);

    sourceSequenceCount = get_source_sequence_count(settings);
    for idxSourceSequence = 1:sourceSequenceCount
        sourceSequenceSeed = networkexp.derive_seed(settings.randomSeed, idxNet, idxSourceSequence, 101);
        sourceNodeOrder = build_source_node_order(settings, sourceSequenceSeed);
        fprintf('  Source sequence %d/%d, seed=%d\n', ...
            idxSourceSequence, sourceSequenceCount, sourceSequenceSeed);

        repeatCells = cell(1, settings.network.N);
        progressState = initialize_progress_state(settings.network.N);
        progressQueue = [];
        if runInParallel && exist('parallel.pool.DataQueue', 'class') == 8
            progressQueue = parallel.pool.DataQueue;
            afterEach(progressQueue, @handle_progress_update);
        end
        if runInParallel
            parfor nPerturbedEdges = 1:settings.network.N
                repeatGroup = run_repeat_group( ...
                    settings, modelSpec, idxNet, netName, ...
                    idxSourceSequence, sourceSequenceSeed, sourceNodeOrder, ...
                    nPerturbedEdges, baselineOmega, baselineNetworkSeed);
                repeatCells{nPerturbedEdges} = repeatGroup;
                if ~isempty(progressQueue)
                    send(progressQueue, pack_progress_payload(repeatGroup));
                end
            end
            if isempty(progressQueue)
                for nPerturbedEdges = 1:settings.network.N
                    progressState = update_progress_state(progressState, ...
                        pack_progress_payload(repeatCells{nPerturbedEdges}));
                end
            end
        else
            for nPerturbedEdges = 1:settings.network.N
                repeatGroup = run_repeat_group( ...
                    settings, modelSpec, idxNet, netName, ...
                    idxSourceSequence, sourceSequenceSeed, sourceNodeOrder, ...
                    nPerturbedEdges, baselineOmega, baselineNetworkSeed);
                repeatCells{nPerturbedEdges} = repeatGroup;
                progressState = update_progress_state(progressState, ...
                    pack_progress_payload(repeatGroup));
            end
        end
        progressState = finalize_progress_state(progressState);
        log_repeat_group_summaries(repeatCells, settings.network.N);

        repeats = [repeatCells{:}];
        experiment = struct( ...
            'schemaVersion', 2, ...
            'schemaName', 'network_ergodic_v2', ...
            'createdAt', char(datetime('now', 'Format', 'yyyyMMdd''T''HHmmss')), ...
            'modelName', modelSpec.name, ...
            'netName', netName, ...
            'weightPer', settings.weightPer, ...
            'numRepeat', settings.numRepeat, ...
            'config', settings, ...
            'solver', struct( ...
                'name', settings.solverName, ...
                'searchWindow', settings.searchWindow), ...
            'seedPolicy', struct( ...
                'masterSeed', settings.randomSeed, ...
                'baselineNetworkSeed', baselineNetworkSeed, ...
                'sourceSequenceSeed', sourceSequenceSeed, ...
                'repeatMode', settings.repeatMode, ...
                'repeatAccountingMode', settings.repeatAccountingMode), ...
            'sourceNodeSequence', struct( ...
                'index', idxSourceSequence, ...
                'seed', sourceSequenceSeed, ...
                'nodeOrder', sourceNodeOrder), ...
            'network', struct( ...
                'baselineWeightMatrix', baselineOmega, ...
                'baselineMetadata', baselineNetworkMetadata), ...
            'baseline', pack_orbit_result(baselineResult), ...
            'repeats', repeats, ...
            'summary', summarize_repeats(repeats));

        if strcmpi(settings.perturbedNodeSelectionMode, 'prefix')
            filePath = fullfile(outputDir, ...
                sprintf('%s (net = %s, weight_per = %s).mat', ...
                modelSpec.name, netName, num2str(settings.weightPer)));
        else
            filePath = fullfile(outputDir, ...
                sprintf('%s (net = %s, source_seq = %d, weight_per = %s).mat', ...
                modelSpec.name, netName, idxSourceSequence, num2str(settings.weightPer)));
        end
        save(filePath, '-struct', 'experiment', '-v7.3');
        log_ergodic_summary(experiment.summary);
        fprintf('  Saved: %s\n', filePath);
        results(end + 1).filePath = filePath; %#ok<AGROW>
        results(end).netName = netName;
        results(end).sourceSequenceIndex = idxSourceSequence;
    end
end

    function handle_progress_update(payload)
        progressState = update_progress_state(progressState, payload);
    end
end

function settings = normalize_ergodic_settings(settings, modelSpec)
settings = ensure_field(settings, 'randomSeed', 1);
settings = ensure_field(settings, 'useParallel', false);
settings = ensure_field(settings, 'numWorkers', []);
settings = ensure_field(settings, 'numRepeat', 100);
settings = ensure_field(settings, 'repeatMode', 'fixedNetwork');
settings = ensure_field(settings, 'repeatAccountingMode', 'fixedAttempts');
settings = ensure_field(settings, 'maxAttemptsMultiplier', 10);
settings = ensure_field(settings, 'perturbedNodeSelectionMode', 'prefix');
settings = ensure_field(settings, 'inputNodeSelectionMode', 'uniformRandomWithReplacement');
settings = ensure_field(settings, 'outputSubdir', 'Ergodic data');
settings = ensure_field(settings, 'solverName', 'ode15s');
settings = ensure_field(settings, 'searchWindow', 1000);
settings = ensure_field(settings, 'nets', {modelSpec.name});

settings.repeatMode = char(string(settings.repeatMode));
settings.repeatAccountingMode = char(string(settings.repeatAccountingMode));
settings.perturbedNodeSelectionMode = char(string(settings.perturbedNodeSelectionMode));
settings.inputNodeSelectionMode = char(string(settings.inputNodeSelectionMode));
settings.outputSubdir = char(string(settings.outputSubdir));
settings.solverName = char(string(settings.solverName));
end

function sourceSequenceCount = get_source_sequence_count(settings)
if strcmpi(settings.perturbedNodeSelectionMode, 'prefix')
    sourceSequenceCount = 1;
else
    sourceSequenceCount = settings.numSourceNodeSequences;
end
end

function sourceNodeOrder = build_source_node_order(settings, sourceSequenceSeed)
numNodes = settings.network.N;
if strcmpi(settings.perturbedNodeSelectionMode, 'prefix')
    sourceNodeOrder = 1:numNodes;
else
    previousRng = rng;
    cleanupObj = onCleanup(@() rng(previousRng));
    rng(sourceSequenceSeed, 'twister');
    sourceNodeOrder = randperm(numNodes);
end
end

function repeatGroup = run_repeat_group( ...
        settings, modelSpec, idxNet, netName, idxSourceSequence, sourceSequenceSeed, ...
        sourceNodeOrder, nPerturbedEdges, baselineOmega, baselineNetworkSeed)
numNodes = settings.network.N;
requestedRepeatCount = settings.numRepeat;
successCount = 0;
candidateCount = 0;
attemptCount = 0;
sourceNodes = sourceNodeOrder(1:nPerturbedEdges);
if strcmpi(settings.repeatAccountingMode, 'untilSuccesses')
    maxAttempts = requestedRepeatCount * settings.maxAttemptsMultiplier;
else
    maxAttempts = requestedRepeatCount;
end
sampleResults = repmat(empty_sample_result(), 1, maxAttempts);

while attemptCount < maxAttempts
    if strcmpi(settings.repeatAccountingMode, 'untilSuccesses') && successCount >= requestedRepeatCount
        break
    end

    attemptCount = attemptCount + 1;
    sampleSeed = networkexp.derive_seed(settings.randomSeed, idxNet, idxSourceSequence, nPerturbedEdges, attemptCount, 1);
    perturbationSeed = networkexp.derive_seed(settings.randomSeed, idxNet, idxSourceSequence, nPerturbedEdges, attemptCount, 2);

    if strcmpi(settings.repeatMode, 'independentNetworkDraws')
        networkSeed = networkexp.derive_seed(settings.randomSeed, idxNet, idxSourceSequence, nPerturbedEdges, attemptCount, 3);
        [baseOmega, networkMetadata] = networkexp.build_network_matrix( ...
            settings.network, netName, networkSeed);
    else
        networkSeed = baselineNetworkSeed;
        baseOmega = baselineOmega;
        networkMetadata = struct( ...
            'netName', netName, ...
            'seed', baselineNetworkSeed, ...
            'numNodes', numNodes, ...
            'degreeAverage', settings.network.degAvg, ...
            'couplingScale', settings.network.K, ...
            'numEdges', nnz(baseOmega), ...
            'density', nnz(baseOmega) / numel(baseOmega));
    end

    perturbation = networkexp.sample_perturbation_from_sources( ...
        settings, sourceNodes, numNodes, perturbationSeed);
    omega = baseOmega + settings.weightPer * perturbation.mask;
    params = modelSpec.buildParams(omega);
    solverOptions = build_solver_options(modelSpec, params);
    poResult = networkexp.evaluate_periodic_orbit( ...
        modelSpec.rhs, ...
        modelSpec.makeInitialState(numNodes), ...
        params, ...
        settings.solverName, ...
        settings.searchWindow, ...
        solverOptions);

    sampleResults(attemptCount).attemptIndex = attemptCount;
    sampleResults(attemptCount).success = poResult.success;
    sampleResults(attemptCount).hasOrbit = poResult.hasOrbit;
    sampleResults(attemptCount).isCandidate = poResult.isCandidate;
    sampleResults(attemptCount).status = poResult.status;
    sampleResults(attemptCount).orbitStatus = poResult.orbitStatus;
    sampleResults(attemptCount).orbitCode = poResult.orbitCode;
    sampleResults(attemptCount).message = poResult.message;
    sampleResults(attemptCount).sampleSeed = sampleSeed;
    sampleResults(attemptCount).sourceSequenceIndex = idxSourceSequence;
    sampleResults(attemptCount).sourceSequenceSeed = sourceSequenceSeed;
    sampleResults(attemptCount).targetRepeatIndex = attemptCount;
    sampleResults(attemptCount).networkSeed = networkSeed;
    sampleResults(attemptCount).perturbationSeed = perturbationSeed;
    sampleResults(attemptCount).perturbation = pack_perturbation(strip_perturbation_mask(perturbation));
    sampleResults(attemptCount).networkSummary = pack_network_summary(networkMetadata);
    sampleResults(attemptCount).observables = pack_observables(poResult.observables);
    sampleResults(attemptCount).diagnostics = pack_diagnostics(poResult.diagnostics);

    if poResult.success
        successCount = successCount + 1;
    end
    if poResult.isCandidate
        candidateCount = candidateCount + 1;
    end
end

repeatGroup = struct( ...
    'nPerturbedEdges', nPerturbedEdges, ...
    'requestedRepeatCount', requestedRepeatCount, ...
    'attemptCount', attemptCount, ...
    'successCount', successCount, ...
    'candidateCount', candidateCount, ...
    'failureCount', attemptCount - successCount, ...
    'attemptLimitReached', attemptCount == maxAttempts && successCount < requestedRepeatCount, ...
    'samples', sampleResults(1:attemptCount));
end

function packed = pack_orbit_result(result)
packed = struct( ...
    'success', result.success, ...
    'hasOrbit', result.hasOrbit, ...
    'isCandidate', result.isCandidate, ...
    'status', result.status, ...
