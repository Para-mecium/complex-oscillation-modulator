function result = run_single_experiment(settings, modelSpec)
%RUN_SINGLE_EXPERIMENT Run one baseline/perturbation network experiment.

settings = normalize_single_settings(settings);
networkDir = fileparts(fileparts(mfilename('fullpath')));
outputDir = fullfile(networkDir, sprintf('%s_%s', modelSpec.name, settings.netName));
ensure_directory(outputDir);
fprintf('Running %s single experiment for %s...\n', modelSpec.name, settings.netName);

baselineNetworkSeed = networkexp.derive_seed(settings.randomSeed, 1);
[omegaOrigin, networkMetadata] = networkexp.build_network_matrix( ...
    settings.network, settings.netName, baselineNetworkSeed);
paramsOrigin = modelSpec.buildParams(omegaOrigin);
baselineSolverOptions = build_solver_options(modelSpec, paramsOrigin);
baselineResult = networkexp.evaluate_periodic_orbit( ...
    modelSpec.rhs, ...
    modelSpec.makeInitialState(settings.network.N), ...
    paramsOrigin, ...
    settings.solverName, ...
    settings.searchWindow, ...
    baselineSolverOptions);
networkexp.log_orbit_result('Baseline', baselineResult);

baselineData = struct( ...
    'schemaVersion', 2, ...
    'experimentKind', 'network_single_baseline', ...
    'createdAt', char(datetime('now', 'Format', 'yyyyMMdd''T''HHmmss')), ...
    'modelName', modelSpec.name, ...
    'netName', settings.netName, ...
    'config', settings, ...
    'network', struct( ...
        'weightMatrix', omegaOrigin, ...
        'metadata', networkMetadata), ...
    'result', pack_orbit_result(baselineResult));

baselineFile = fullfile(outputDir, ...
    sprintf('TS_init_%s (%s, N = %d).mat', ...
    modelSpec.name, settings.netName, settings.network.N));
TS_ori = baselineResult.TS;
amp_var_ori = baselineResult.observables.amplitude;
period_ori = baselineResult.observables.period;
max_var_ori = baselineResult.observables.maxVariable;
min_var_ori = baselineResult.observables.minVariable;
params = paramsOrigin;
omega_origin = omegaOrigin;
save(baselineFile, ...
    'baselineData', 'TS_ori', 'amp_var_ori', 'period_ori', ...
    'max_var_ori', 'min_var_ori', 'params', 'omega_origin');
fprintf('  Saved baseline: %s\n', baselineFile);

perturbationSeed = networkexp.derive_seed(settings.randomSeed, 2, settings.nPerturbedEdges);
perturbation = networkexp.sample_perturbation( ...
    settings, settings.nPerturbedEdges, settings.network.N, perturbationSeed);
omegaPerturbed = omegaOrigin + settings.weightPer * perturbation.mask;
perturbedNetworkMetadata = struct( ...
    'netName', settings.netName, ...
    'seed', baselineNetworkSeed, ...
    'numNodes', settings.network.N, ...
    'numEdges', nnz(omegaPerturbed), ...
    'density', nnz(omegaPerturbed) / numel(omegaPerturbed));
paramsPerturbed = modelSpec.buildParams(omegaPerturbed);
perturbedSolverOptions = build_solver_options(modelSpec, paramsPerturbed);
perturbedResult = networkexp.evaluate_periodic_orbit( ...
    modelSpec.rhs, ...
    modelSpec.makeInitialState(settings.network.N), ...
    paramsPerturbed, ...
    settings.solverName, ...
    settings.searchWindow, ...
    perturbedSolverOptions);
networkexp.log_orbit_result('Perturbation', perturbedResult);

edges_per_G = map_graph_edge_indices(omegaPerturbed, perturbation.edges);
perturbedData = struct( ...
    'schemaVersion', 2, ...
    'experimentKind', 'network_single_perturbation', ...
    'createdAt', char(datetime('now', 'Format', 'yyyyMMdd''T''HHmmss')), ...
    'modelName', modelSpec.name, ...
    'netName', settings.netName, ...
    'config', settings, ...
    'network', struct( ...
        'weightMatrix', omegaPerturbed, ...
        'metadata', perturbedNetworkMetadata), ...
    'perturbation', strip_perturbation_mask(perturbation), ...
    'result', pack_orbit_result(perturbedResult));

perturbedFile = fullfile(outputDir, ...
    sprintf('TS_per_%d_%s (%s, N = %d).mat', ...
    settings.nPerturbedEdges, modelSpec.name, settings.netName, settings.network.N));
TS = perturbedResult.TS;
amp_var = perturbedResult.observables.amplitude;
period = perturbedResult.observables.period;
max_var = perturbedResult.observables.maxVariable;
min_var = perturbedResult.observables.minVariable;
params = paramsPerturbed;
save(perturbedFile, ...
    'perturbedData', 'TS', 'amp_var', 'period', ...
    'max_var', 'min_var', 'edges_per_G', 'params');
fprintf('  Saved perturbation: %s\n', perturbedFile);

result = struct( ...
    'baselineFile', baselineFile, ...
    'perturbedFile', perturbedFile, ...
    'baselineData', baselineData, ...
    'perturbedData', perturbedData);
end

function settings = normalize_single_settings(settings)
settings = ensure_field(settings, 'randomSeed', 1);
settings = ensure_field(settings, 'weightPer', 0.5);
settings = ensure_field(settings, 'nPerturbedEdges', 50);
settings = ensure_field(settings, 'perturbedNodeSelectionMode', 'prefix');
settings = ensure_field(settings, 'inputNodeSelectionMode', 'uniformRandomWithReplacement');
settings = ensure_field(settings, 'solverName', 'ode15s');
settings = ensure_field(settings, 'searchWindow', 1000);

settings.netName = char(string(settings.netName));
settings.perturbedNodeSelectionMode = char(string(settings.perturbedNodeSelectionMode));
settings.inputNodeSelectionMode = char(string(settings.inputNodeSelectionMode));
settings.solverName = char(string(settings.solverName));
end

function packed = pack_orbit_result(result)
packed = struct( ...
    'success', result.success, ...
    'hasOrbit', result.hasOrbit, ...
    'isCandidate', result.isCandidate, ...
    'status', result.status, ...
    'orbitStatus', result.orbitStatus, ...
    'orbitCode', result.orbitCode, ...
    'message', result.message, ...
    'TS', {result.TS}, ...
    'observables', result.observables, ...
    'diagnostics', result.diagnostics);
end

function edgeIndices = map_graph_edge_indices(omega, edges)
graphObj = digraph(omega);
[tf, edgeIndices] = ismember(edges, graphObj.Edges.EndNodes, 'rows');
if any(~tf)
    edgeIndices = [];
end
edgeIndices = reshape(edgeIndices, [], 1);
end

function perturbation = strip_perturbation_mask(perturbation)
perturbation = rmfield(perturbation, 'mask');
end

function settings = ensure_field(settings, name, defaultValue)
if ~isfield(settings, name) || isempty(settings.(name))
    settings.(name) = defaultValue;
end
end

function ensure_directory(folderPath)
if exist(folderPath, 'dir') ~= 7
    mkdir(folderPath);
end
end

function solverOptions = build_solver_options(modelSpec, params)
solverOptions = struct();
if ~isfield(modelSpec, 'buildSolverOptions') || isempty(modelSpec.buildSolverOptions)
    return
end

solverOptions = modelSpec.buildSolverOptions(params);
if isempty(solverOptions)
    solverOptions = struct();
elseif ~isstruct(solverOptions)
    error('networkexp:InvalidModelSolverOptions', ...
        'modelSpec.buildSolverOptions must return a struct or [].');
end
end
