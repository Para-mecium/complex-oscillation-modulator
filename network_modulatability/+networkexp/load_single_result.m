function data = load_single_result(filePath)
%LOAD_SINGLE_RESULT Normalize legacy and refactored single-run saves.

raw = load(filePath);

if isfield(raw, 'baselineData')
    result = raw.baselineData.result;
    data = struct( ...
        'kind', 'baseline', ...
        'TS', {result.TS}, ...
        'amplitude', result.observables.amplitude, ...
        'period', result.observables.period, ...
        'maxVariable', result.observables.maxVariable, ...
        'minVariable', result.observables.minVariable, ...
        'weightMatrix', raw.baselineData.network.weightMatrix, ...
        'edgeIndices', [], ...
        'perturbationEdges', [], ...
        'nodeCount', floor(numel(result.observables.amplitude) / 2));
    return
end

if isfield(raw, 'perturbedData')
    result = raw.perturbedData.result;
    edgeIndices = [];
    if isfield(raw, 'edges_per_G')
        edgeIndices = raw.edges_per_G;
    end
    perturbationEdges = [];
    if isfield(raw.perturbedData, 'perturbation') && ...
            isfield(raw.perturbedData.perturbation, 'edges')
        perturbationEdges = raw.perturbedData.perturbation.edges;
    elseif ~isempty(edgeIndices)
        perturbationEdges = edge_indices_to_end_nodes( ...
            raw.perturbedData.network.weightMatrix, edgeIndices);
    end
    data = struct( ...
        'kind', 'perturbed', ...
        'TS', {result.TS}, ...
        'amplitude', result.observables.amplitude, ...
        'period', result.observables.period, ...
        'maxVariable', result.observables.maxVariable, ...
        'minVariable', result.observables.minVariable, ...
        'weightMatrix', raw.perturbedData.network.weightMatrix, ...
        'edgeIndices', edgeIndices, ...
        'perturbationEdges', perturbationEdges, ...
        'nodeCount', floor(numel(result.observables.amplitude) / 2));
    return
end

if isfield(raw, 'TS_ori')
    data = struct( ...
        'kind', 'baseline', ...
        'TS', {raw.TS_ori}, ...
        'amplitude', raw.amp_var_ori, ...
        'period', raw.period_ori, ...
        'maxVariable', raw.max_var_ori, ...
        'minVariable', raw.min_var_ori, ...
        'weightMatrix', raw.omega_origin, ...
        'edgeIndices', [], ...
        'perturbationEdges', [], ...
        'nodeCount', floor(numel(raw.amp_var_ori) / 2));
    return
end

if isfield(raw, 'TS')
    edgeIndices = [];
    if isfield(raw, 'edges_per_G')
        edgeIndices = raw.edges_per_G;
    end
    perturbationEdges = [];
    if ~isempty(edgeIndices)
        perturbationEdges = edge_indices_to_end_nodes(raw.params{end}, edgeIndices);
    end
    data = struct( ...
        'kind', 'perturbed', ...
        'TS', {raw.TS}, ...
        'amplitude', raw.amp_var, ...
        'period', raw.period, ...
        'maxVariable', raw.max_var, ...
        'minVariable', raw.min_var, ...
        'weightMatrix', raw.params{end}, ...
        'edgeIndices', edgeIndices, ...
        'perturbationEdges', perturbationEdges, ...
        'nodeCount', floor(numel(raw.amp_var) / 2));
    return
end

error('networkexp:UnknownSingleResultSchema', ...
    'Could not recognize single-run schema in %s.', filePath);
end

function endNodes = edge_indices_to_end_nodes(weightMatrix, edgeIndices)
graphObj = digraph(spones(sparse(weightMatrix)));
edgeIndices = edgeIndices(:);
edgeIndices = edgeIndices(edgeIndices >= 1 & edgeIndices <= numedges(graphObj));
if isempty(edgeIndices)
    endNodes = [];
else
    endNodes = graphObj.Edges.EndNodes(edgeIndices, :);
end
end
