function cmap = warm_colormap()
n = 256;
t = linspace(0, 1, n).';
c1 = [1.00, 0.55, 0.14];
c2 = [0.98, 0.96, 0.92];
cmap = (1 - t) .* c1 + t .* c2;
end

function cmap = cool_colormap()
n = 256;
t = linspace(0, 1, n).';
c1 = [0.05, 0.25, 0.60];
c2 = [0.92, 0.95, 0.98];
cmap = (1 - t) .* c1 + t .* c2;
end
