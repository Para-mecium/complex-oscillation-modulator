function cmap = warm_colormap()
n = 256;
t = linspace(0, 1, n).';
c1 = [1.0, 0.65, 0.22];
c2 = [0.98, 0.96, 0.92];
cmap = (1 - t) .* c1 + t .* c2;
end

function cmap = cool_colormap()
n = 256;
t = linspace(0, 1, n).';
c1 = [0.05, 0.25, 0.55];
c2 = [0.88, 0.93, 0.97];
cmap = (1 - t) .* c1 + t .* c2;
end
