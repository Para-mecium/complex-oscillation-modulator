function setup(testCase)
global RUN_MODULATION_TASK_LOG FLEX_FIND_ORBIT_LOG
RUN_MODULATION_TASK_LOG = {};
FLEX_FIND_ORBIT_LOG = {};

stubDir = tempname;
mkdir(stubDir);
mkdir(fullfile(stubDir, '+flexmod'));
write_run_modulation_task_stub(stubDir);
write_flexmod_find_orbit_stub(fullfile(stubDir, '+flexmod'));
write_base_bifurcation_stub(stubDir);

flexmod.ensure_paths();
addpath(stubDir, '-begin');
clear run_modulation_task
clear flexmod.find_orbit
clear base_bifurcation_curve

testCase.TestData.stubDir = stubDir;
testCase.TestData.cleanupPath = onCleanup(@() cleanup_stub_dir(stubDir));
end

function teardown(~)
global RUN_MODULATION_TASK_LOG FLEX_FIND_ORBIT_LOG
RUN_MODULATION_TASK_LOG = {};
FLEX_FIND_ORBIT_LOG = {};
close all force
end

function testBuildFig3CurveCachesAndIndependentMarks(testCase)
global RUN_MODULATION_TASK_LOG

cfg = make_test_cfg();
curveData3c = build_fig3c_data(cfg);
curveLogs3c = RUN_MODULATION_TASK_LOG;
verifyEqual(testCase, numel(curveData3c.curves), 2);
verifyEqual(testCase, numel(curveData3c.curveFiles), 2);
verifyTrue(testCase, all(cellfun(@isfile, curveData3c.curveFiles)));
verifyEqual(testCase, numel(filter_logs(curveLogs3c, {'period', 'amplitude'})), 2);
verifyEqual(testCase, numel(filter_logs(curveLogs3c, {'period', 'I1'})), 4);

RUN_MODULATION_TASK_LOG = {};
markData3c = build_fig3c_marks(cfg);
verifyTrue(testCase, all(cellfun(@isfile, markData3c.markFiles)));
markLogs3c = RUN_MODULATION_TASK_LOG;
verifyEqual(testCase, numel(markLogs3c), numel(cfg.fig3c.markAmplitudes));
for i = 1:numel(markLogs3c)
    verifyEqual(testCase, markLogs3c{i}.startParams, cfg.fig3c.markSeeds(i, :), 'AbsTol', 1e-12);
end

RUN_MODULATION_TASK_LOG = {};
curveData3d = build_fig3d_data(cfg);
curveLogs3d = RUN_MODULATION_TASK_LOG;
verifyEqual(testCase, numel(curveData3d.curves), 2);
verifyEqual(testCase, numel(curveData3d.curveFiles), 2);
verifyTrue(testCase, all(cellfun(@isfile, curveData3d.curveFiles)));
verifyEqual(testCase, numel(filter_logs(curveLogs3d, {'amplitude', 'period'})), 2);
verifyEqual(testCase, numel(filter_logs(curveLogs3d, {'amplitude', 'I1'})), 4);

RUN_MODULATION_TASK_LOG = {};
markData3d = build_fig3d_marks(cfg);
verifyTrue(testCase, all(cellfun(@isfile, markData3d.markFiles)));
markLogs3d = RUN_MODULATION_TASK_LOG;
verifyEqual(testCase, numel(markLogs3d), numel(cfg.fig3d.markPeriods));
for i = 1:numel(markLogs3d)
    verifyEqual(testCase, markLogs3d{i}.startParams, cfg.fig3d.markSeeds(i, :), 'AbsTol', 1e-12);
end
end

