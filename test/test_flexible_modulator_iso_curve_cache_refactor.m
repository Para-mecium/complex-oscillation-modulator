end

function cleanup_stub_dir(stubDir)
if isfolder(stubDir)
    rmpath(stubDir);
    clear run_modulation_task
    clear flexmod.find_orbit
    clear base_bifurcation_curve
    try
        rmdir(stubDir, 's');
    catch
    end
end
end

function write_run_modulation_task_stub(stubDir)
stubPath = fullfile(stubDir, 'run_modulation_task.m');
fid = fopen(stubPath, 'w');
assert(fid >= 0, 'Failed to create run_modulation_task stub.');
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

lines = { ...
    'function result = run_modulation_task(cfg)', ...
    'global RUN_MODULATION_TASK_LOG', ...
    'if isempty(RUN_MODULATION_TASK_LOG), RUN_MODULATION_TASK_LOG = {}; end', ...
    'RUN_MODULATION_TASK_LOG{end + 1} = struct(''startParams'', reshape(cfg.startParams, 1, []), ''goalOrder'', {cfg.goalOrder}, ''goals'', cfg.goals);', ...
    'goalOrder = cfg.goalOrder;', ...
    'if isequal(goalOrder, {''period'', ''amplitude''})', ...
    '    result = make_period_amplitude_result(cfg);', ...
    'elseif isequal(goalOrder, {''period'', ''I1''})', ...
    '    result = make_period_i1_branch(cfg);', ...
    'elseif isequal(goalOrder, {''amplitude'', ''period''})', ...
    '    result = make_amplitude_period_seed(cfg);', ...
    'elseif isequal(goalOrder, {''amplitude'', ''I1''})', ...
    '    result = make_amplitude_i1_branch(cfg);', ...
    'else', ...
    '    error(''test:UnexpectedGoalOrder'', ''Unexpected goalOrder in stub.'');', ...
    'end', ...
    'end', ...
    '', ...
    'function result = make_period_amplitude_result(cfg)', ...
    'params = reshape(cfg.startParams, 1, []);', ...
    'if isfield(cfg, ''modelType'') && strcmp(cfg.modelType, ''temperature'')', ...
    '    pathParams = [params; params + [0.1, -1.5]; params + [0.2, -3.0]];', ...
    'else', ...
    '    pathParams = [params; params + [0.05, 0.08]; params + [0.10, 0.12]];', ...
    'end', ...
    'period = linspace(cfg.goals.period + 2, cfg.goals.period, size(pathParams, 1)).'';', ...
    'amplitude = linspace(max(cfg.goals.amplitude - 0.5, 0.1), cfg.goals.amplitude, size(pathParams, 1)).'';', ...
    'result = make_result(pathParams(end, :), period(end), amplitude(end), make_path(pathParams, period, amplitude, ''target_reached''));', ...
    'end', ...
    '', ...
    'function result = make_period_i1_branch(cfg)', ...
    'params = reshape(cfg.startParams, 1, []);', ...
    'targetI1 = cfg.goals.I1;', ...
    'etValues = [params(2); params(2) + 0.12 * sign(targetI1 - params(1) + eps)];', ...
    'paramMatrix = [params(1), etValues(1); targetI1, etValues(2)];', ...
    'period = cfg.goals.period * ones(2, 1);', ...
    'amplitude = [1.8; 2.4] + 0.2 * sign(targetI1 - params(1));', ...
    'result = make_result(paramMatrix(end, :), period(end), amplitude(end), make_path(paramMatrix, period, amplitude, ''target_reached''));', ...
    'end', ...
    '', ...
    'function result = make_amplitude_period_seed(cfg)', ...
    'params = reshape(cfg.startParams, 1, []);', ...
    'period = cfg.goals.period;', ...
    'amplitude = cfg.goals.amplitude;', ...
    'result = make_result(params, period, amplitude, make_path([params; params + [0.02, 0.02]], [period; period], [amplitude; amplitude], ''target_reached''));', ...
    'end', ...
    '', ...
    'function result = make_amplitude_i1_branch(cfg)', ...
    'params = reshape(cfg.startParams, 1, []);', ...
    'targetI1 = cfg.goals.I1;', ...
    'etValues = [params(2); params(2) + 0.10 * sign(targetI1 - params(1) + eps)];', ...
    'paramMatrix = [params(1), etValues(1); targetI1, etValues(2)];', ...
    'period = [cfg.goals.amplitude * 20 + 18; cfg.goals.amplitude * 20 + 20];', ...
    'amplitude = cfg.goals.amplitude * [1; 1];', ...
    'result = make_result(paramMatrix(end, :), period(end), amplitude(end), make_path(paramMatrix, period, amplitude, ''target_reached''));', ...
    'end', ...
    '', ...
    'function result = make_result(params, period, amplitude, path)', ...
    'orbit = make_orbit(period, params, amplitude);', ...
    'result = struct();', ...
    'result.params = reshape(params, 1, []);', ...
    'result.orbit = orbit;', ...
    'result.path = path;', ...
    'result.measures = struct(''period'', period, ''amplitude'', amplitude, ''y_max'', amplitude + 3, ''y_min'', 3 - amplitude);', ...
    'result.solverView = struct(''params'', reshape(params, 1, []));', ...
    'result.derivedView = struct(''period'', period, ''varAmp'', [0 amplitude], ''varMax'', [0 amplitude + 3], ''varMin'', [0 3 - amplitude]);', ...
    'end', ...
    '', ...
    'function path = make_path(paramMatrix, period, amplitude, stopReason)', ...
    'path = struct();', ...
    'path.paramNames = {''I1'', ''ET''};', ...
    'path.paramMatrix = paramMatrix;', ...
    'path.period = period(:);', ...
    'path.amplitude = amplitude(:);', ...
    'path.yMax = amplitude(:) + 3;', ...
    'path.yMin = 3 - amplitude(:);', ...
    'path.lambda = linspace(0, 1, size(paramMatrix, 1)).'';', ...
    'path.directConditionEstimate = ones(size(paramMatrix, 1), 1);', ...
    'path.finalConditionEstimate = ones(size(paramMatrix, 1), 1);', ...
    'path.success = true(size(paramMatrix, 1), 1);', ...
    'path.stopReason = stopReason;', ...
    'path.stopLambda = 1;', ...
    'path.stopTriggerValue = NaN;', ...
    'end', ...
    '', ...
    'function orbit = make_orbit(period, params, amplitude)', ...
    't = linspace(0, max(period, 1), 8).'';', ...
    'y = 3 + amplitude * sin(2 * pi * t / max(period, eps));', ...
    'orbit = struct();', ...
    'orbit.t = t;', ...
    'orbit.y = [zeros(size(t)), y];', ...
    'orbit.period = period;', ...
    'orbit.params = params;', ...
    'orbit.amplitude = amplitude;', ...
    'orbit.yMax = max(y);', ...
    'orbit.yMin = min(y);', ...
    'orbit.success = true;', ...
    'orbit.message = '''';', ...
    'end'};
fprintf(fid, '%s\n', lines{:});
end

