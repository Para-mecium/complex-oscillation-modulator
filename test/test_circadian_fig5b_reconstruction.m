assert(fid >= 0, 'Failed to create run_circadian_fmam_task stub.');
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

lines = { ...
    'function result = run_circadian_fmam_task(cfg)', ...
    'global RUN_MODULATION_TASK_LOG', ...
    'if isempty(RUN_MODULATION_TASK_LOG), RUN_MODULATION_TASK_LOG = {}; end', ...
    'startParams = resolve_start_params(cfg);', ...
    'RUN_MODULATION_TASK_LOG{end + 1} = struct(''startParams'', startParams, ''goalOrder'', {cfg.goalOrder}, ''goals'', cfg.goals);', ...
    'goalOrder = cfg.goalOrder;', ...
    'if isequal(goalOrder, {''period'', ''AT''})', ...
    '    params = [startParams(1), cfg.goals.AT];', ...
    '    amplitude = max(cfg.goals.AT * 0.5, 0.005);', ...
    '    maximum = amplitude + 0.10;', ...
    '    result = make_result({''Kd'', ''AT''}, params, cfg.goals.period, amplitude, maximum, []);', ...
    'elseif isequal(goalOrder, {''period'', ''Kd''})', ...
    '    result = make_period_kd_branch(cfg);', ...
    'elseif isequal(goalOrder, {''period'', ''amplitude''})', ...
    '    params = startParams;', ...
    '    result = make_result({''Kd'', ''AT''}, params, cfg.goals.period, cfg.goals.amplitude, cfg.goals.amplitude + 0.10, []);', ...
    'elseif isequal(goalOrder, {''maximum'', ''AT''})', ...
    '    params = [startParams(1), cfg.goals.AT];', ...
