function tests = test_circadian_fig5b_reconstruction
%TEST_CIRCADIAN_FIG5B_RECONSTRUCTION Regression coverage for circadian per-curve caches.

tests = functiontests(localfunctions);
end

function setupOnce(testCase)
testDir = fileparts(mfilename('fullpath'));
rootDir = fileparts(testDir);
addpath(rootDir, '-begin');
addpath(fullfile(rootDir, 'Circadian'), '-begin');
testCase.TestData.rootDir = rootDir;
end

function setup(testCase)
global RUN_MODULATION_TASK_LOG
RUN_MODULATION_TASK_LOG = {};

stubDir = tempname;
mkdir(stubDir);
write_run_circadian_fmam_task_stub(stubDir);

circadian.ensure_paths();
addpath(stubDir, '-begin');
clear run_circadian_fmam_task

testCase.TestData.stubDir = stubDir;
testCase.TestData.cleanupPath = onCleanup(@() cleanup_stub_dir(stubDir));
end

function teardown(~)
global RUN_MODULATION_TASK_LOG
RUN_MODULATION_TASK_LOG = {};
close all force
end

function testBuildFig5bProducesOneCurveCachePerIsoLineAndIndependentMarks(testCase)
global RUN_MODULATION_TASK_LOG

cfg = make_test_cfg();
curveData = build_fig5b_data(cfg);
curveLogs = RUN_MODULATION_TASK_LOG;

verifyEqual(testCase, numel(curveData.curves), 1);
verifyEqual(testCase, numel(curveData.curveFiles), 1);
verifyTrue(testCase, isfile(curveData.curveFiles{1}));

curve = curveData.curves{1};
branchNames = {'lowerLeft', 'lowerRight', 'upperLeft', 'upperRight'};
for i = 1:numel(branchNames)
    branch = curve.branches.(branchNames{i});
    verifyTrue(testCase, all(isfield(branch, ...
        {'paramMatrix', 'Kd', 'AT', 'period', 'obsAmplitude', 'obsMax', ...
         'directConditionEstimate', 'stopReason'})));
    verifyGreaterThanOrEqual(testCase, numel(branch.Kd), 1);
    verifyEqual(testCase, issorted(branch.Kd), true);
end

verifyEqual(testCase, sort(unique(curve.allPoints.branchId)), sort(branchNames(:)));
verifyEqual(testCase, size(curve.allPoints.paramMatrix, 1), 8);

verifyEqual(testCase, numel(curveLogs), 6);
verifyEqual(testCase, numel(filter_logs(curveLogs, {'period', 'AT'})), 2);
verifyEqual(testCase, numel(filter_logs(curveLogs, {'period', 'Kd'})), 4);

RUN_MODULATION_TASK_LOG = {};
markData = build_fig5b_marks(cfg);
markLogs = RUN_MODULATION_TASK_LOG;

verifyEqual(testCase, numel(markData.markFiles), numel(cfg.fig5b.markAmplitudes));
verifyTrue(testCase, all(cellfun(@isfile, markData.markFiles)));
verifyEqual(testCase, numel(markLogs), numel(cfg.fig5b.markAmplitudes));
for i = 1:numel(markLogs)
    verifyEqual(testCase, markLogs{i}.startParams, cfg.fig5b.markSeeds(i, :), 'AbsTol', 1e-12);
end
end

function testBuildFig5cUsesMarkCachesWithoutCurveCaches(testCase)
global RUN_MODULATION_TASK_LOG

cfg = make_test_cfg();
markData = build_fig5b_marks(cfg);
verifyTrue(testCase, all(cellfun(@isfile, markData.markFiles)));

RUN_MODULATION_TASK_LOG = {};
data = build_fig5c_data(cfg);

verifyEqual(testCase, numel(RUN_MODULATION_TASK_LOG), 0);
verifyEqual(testCase, numel(data.series), numel(cfg.fig5b.markAmplitudes));
verifyEqual(testCase, data.markAmplitudes, cfg.fig5b.markAmplitudes, 'AbsTol', 1e-12);
end

function testReproduceAllFig5BuildsPerCurveAndPerMarkCachesFromEmptyRoot(testCase)
cfg = make_test_cfg();
cfg.fig5d.maxima = [0.12, 0.10];
cfg.fig5d.ATseed = [0.045, 0.03];
cfg.fig5d.Kdseed = [5e-5, 5e-5];
cfg.fig5d.markPeriods = [23.5, 24];
cfg.fig5d.markSeeds = [8.5e-5, 0.045; 6.5e-5, 0.035];
cfg.fig5d.sde.representativeSeeds = [1, 2];
cfg.figS2a.amplitudes = [0.02, 0.03];

result = reproduce_all_fig5(cfg);

verifyTrue(testCase, isfile(circadian.curve_cache_file(cfg, 'fig5b', 'period', cfg.fig5b.periods(1))));
verifyTrue(testCase, isfile(circadian.curve_cache_file(cfg, 'fig5d', 'maximum', cfg.fig5d.maxima(1))));
verifyTrue(testCase, isfile(circadian.curve_cache_file(cfg, 'figS2a', 'amplitude', cfg.figS2a.amplitudes(1))));
verifyTrue(testCase, isfile(circadian.mark_cache_file(cfg, 'fig5b', 'amplitude_01')));
verifyTrue(testCase, isfile(circadian.mark_cache_file(cfg, 'fig5d', 'period_01')));

verifyTrue(testCase, isgraphics(result.fig5b.figure));
verifyTrue(testCase, isgraphics(result.fig5c.figure));
verifyTrue(testCase, isgraphics(result.fig5d.figure));
verifyTrue(testCase, isgraphics(result.figS2a.figure));
end

function entries = filter_logs(logEntries, goalOrder)
mask = cellfun(@(entry) isequal(entry.goalOrder, goalOrder), logEntries);
entries = logEntries(mask);
end

