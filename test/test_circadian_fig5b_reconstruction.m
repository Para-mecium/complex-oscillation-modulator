function cleanup_stub_dir(stubDir)
if isfolder(stubDir)
    rmpath(stubDir);
    clear run_circadian_fmam_task
    try
        rmdir(stubDir, 's');
    catch
    end
end
end

function write_run_circadian_fmam_task_stub(stubDir)
