function result = po_initialize_result(y0, solverUsed)
if nargin < 2 || strlength(string(solverUsed)) == 0
    solverUsed = "direct";
end

solverUsed = string(solverUsed);
nState = numel(y0);
backendUsed = "direct";
if solverUsed == "matcont"
    backendUsed = "matcont_orbit";
end

result = struct( ...
    'success', false, ...
    'has_orbit', false, ...
    'status', "", ...
    'code', NaN, ...
    'message', "", ...
    'period', [], ...
    'orbit_t', [], ...
    'orbit_y', zeros(0, nState), ...
    'amplitude', [], ...
    'max_variable', [], ...
    'min_variable', [], ...
    'solver_used', solverUsed, ...
    'event_times', zeros(0, 1), ...
    'event_states', zeros(0, nState), ...
    'backend_used', backendUsed, ...
    'orbit', struct(), ...
    'input_parameter_values', zeros(1, 0), ...
    'output_parameter_values', zeros(1, 0), ...
    'active_parameter_index', [], ...
    'input_active_parameter_value', NaN, ...
    'seed_corrected_parameter_value', NaN, ...
    'output_active_parameter_value', NaN, ...
    'parameter_error', NaN, ...
    'parameter_status', "", ...
    'diagnostics', struct(), ...
    'raw', struct());
end
